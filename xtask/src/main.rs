//! Repository automation, run as `cargo xtask <task>`.

use std::{
    collections::{BTreeMap, BTreeSet},
    env, fs,
    path::Path,
};

use anyhow::{Context, Result, bail};
use serde::Deserialize;
use touchcue::cli::Cli;

const USAGE_SPEC: &str = "touchcue.usage.kdl";
const LOCALES: [&str; 2] = ["pl", "de"];
const LABELS: [&str; 5] = ["Usage", "Global Flags", "Flags", "Arguments", "Subcommands"];

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Translations {
    spec: BTreeMap<String, String>,
    markdown: BTreeMap<String, String>,
}

fn main() -> Result<()> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .context("xtask manifest directory has no parent")?;
    match env::args().nth(1).as_deref() {
        Some("render") => render(root),
        Some("translate-markdown") => translate_markdown(root),
        _ => bail!("usage: cargo xtask <render|translate-markdown>"),
    }
}

#[tracing::instrument(skip_all, err)]
fn table(root: &Path, locale: &str) -> Result<Translations> {
    let path = root.join(format!("xtask/i18n/{locale}.toml"));
    let source =
        fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))?;
    toml::from_str(&source).with_context(|| format!("parsing {}", path.display()))
}

/// Writes version-independent English and translated usage specs.
#[tracing::instrument(skip_all, err)]
fn render(root: &Path) -> Result<()> {
    let mut spec = String::from("// @generated by usage-rs from the touchcue CLI definition\n");
    for line in Cli::to_kdl().lines() {
        if !line.starts_with("version ") {
            spec.push_str(line);
            spec.push('\n');
        }
    }
    spec.truncate(spec.trim_end().len());
    spec.push('\n');
    let mut translated = Vec::new();
    for locale in LOCALES {
        let translations = table(root, locale)?;
        let output = translate_spec(&spec, &translations)
            .with_context(|| format!("validating {locale} translations"))?;
        translated.push((locale, output));
    }
    fs::write(root.join(USAGE_SPEC), &spec).context("writing English usage spec")?;
    let directory = root.join("target/usage");
    fs::create_dir_all(&directory).context("creating target/usage")?;
    for (locale, output) in translated {
        fs::write(
            directory.join(format!("touchcue.{locale}.usage.kdl")),
            output,
        )
        .with_context(|| format!("writing {locale} usage spec"))?;
    }
    Ok(())
}

fn validate_keys(used: &BTreeSet<String>, entries: &BTreeMap<String, String>) -> Result<()> {
    let keys: BTreeSet<_> = entries.keys().cloned().collect();
    let missing: Vec<_> = used.difference(&keys).collect();
    let stale: Vec<_> = keys.difference(used).collect();
    let empty: Vec<_> = entries
        .iter()
        .filter(|(_, value)| value.trim().is_empty())
        .map(|(key, _)| key)
        .collect();
    if !missing.is_empty() || !stale.is_empty() || !empty.is_empty() {
        bail!(
            "missing translations: {missing:#?}; stale entries: {stale:#?}; empty translations: {empty:#?}"
        );
    }
    Ok(())
}

fn prose_key(key: &str) -> bool {
    matches!(
        key,
        "about"
            | "long_about"
            | "help"
            | "long_help"
            | "help_heading"
            | "before_help"
            | "after_help"
            | "before_long_help"
            | "after_long_help"
    )
}

// Returns a decoded token and its byte length in usage-rs's generated KDL.
fn token(source: &str) -> Result<(String, usize)> {
    let hashes = source.bytes().take_while(|byte| *byte == b'#').count();
    if source[hashes..].starts_with("\"\"\"\n") {
        let start = hashes + 4;
        let close = format!("\n\"\"\"{}", "#".repeat(hashes));
        let end = source[start..]
            .find(&close)
            .context("unterminated KDL multiline string")?
            + start;
        return Ok((source[start..end].to_owned(), end + close.len()));
    }
    if !source.starts_with('"') {
        let end = source
            .find(|ch: char| ch.is_whitespace() || matches!(ch, '=' | '{' | '}'))
            .unwrap_or(source.len());
        if end == 0 {
            bail!("expected KDL token near {source:?}");
        }
        return Ok((source[..end].to_owned(), end));
    }
    let mut value = String::new();
    let mut chars = source.char_indices().skip(1);
    while let Some((offset, ch)) = chars.next() {
        match ch {
            '"' => return Ok((value, offset + 1)),
            '\\' => {
                let (_, escaped) = chars.next().context("unterminated KDL escape")?;
                match escaped {
                    '"' | '\\' => value.push(escaped),
                    'n' => value.push('\n'),
                    'r' => value.push('\r'),
                    't' => value.push('\t'),
                    'u' => {
                        if chars.next().map(|(_, ch)| ch) != Some('{') {
                            bail!("invalid KDL Unicode escape");
                        }
                        let mut hex = String::new();
                        loop {
                            let (_, ch) =
                                chars.next().context("unterminated KDL Unicode escape")?;
                            if ch == '}' {
                                break;
                            }
                            hex.push(ch);
                        }
                        let scalar =
                            u32::from_str_radix(&hex, 16).context("invalid KDL Unicode escape")?;
                        value.push(char::from_u32(scalar).context("invalid KDL Unicode scalar")?);
                    }
                    _ => bail!("unsupported generated KDL escape: {escaped:?}"),
                }
            }
            _ => value.push(ch),
        }
    }
    bail!("unterminated KDL string")
}

fn quote(value: &str) -> String {
    let mut output = String::from("\"");
    for ch in value.chars() {
        match ch {
            '"' => output.push_str("\\\""),
            '\\' => output.push_str("\\\\"),
            '\n' => output.push_str("\\n"),
            '\r' => output.push_str("\\r"),
            '\t' => output.push_str("\\t"),
            ch if ch.is_control() => output.extend(ch.escape_unicode()),
            _ => output.push(ch),
        }
    }
    output.push('"');
    output
}

fn translate_spec(source: &str, translations: &Translations) -> Result<String> {
    let mut used = BTreeSet::new();
    let mut replacements = Vec::new();
    let mut offset = 0;
    while offset < source.len() {
        let rest = &source[offset..];
        if rest.starts_with("//") {
            offset += rest.find('\n').unwrap_or(rest.len());
        } else if rest.starts_with(|ch: char| ch.is_whitespace() || matches!(ch, '=' | '{' | '}')) {
            offset += 1;
        } else {
            let node_name = source[..offset]
                .rsplit('\n')
                .next()
                .is_some_and(|line| line.trim().is_empty());
            let (key, length) = token(rest)?;
            offset += length;
            let property = source[offset..].starts_with('=');
            if (node_name || property) && prose_key(&key) {
                let rest = &source[offset..];
                offset += rest.len()
                    - rest
                        .trim_start_matches(|ch: char| ch.is_whitespace() || ch == '=')
                        .len();
                let (value, length) = token(&source[offset..])?;
                used.insert(value.clone());
                if let Some(translated) = translations.spec.get(&value) {
                    replacements.push((offset, offset + length, quote(translated)));
                }
                offset += length;
            }
        }
    }
    validate_keys(&used, &translations.spec)?;
    validate_keys(
        &LABELS.into_iter().map(str::to_owned).collect(),
        &translations.markdown,
    )?;
    let mut output = source.to_owned();
    for (start, end, replacement) in replacements.into_iter().rev() {
        output.replace_range(start..end, &replacement);
    }
    Ok(output)
}

#[tracing::instrument(skip_all, err)]
fn translate_markdown(root: &Path) -> Result<()> {
    for locale in LOCALES {
        let translations = table(root, locale)?;
        translate_spec(
            &fs::read_to_string(root.join(USAGE_SPEC)).context("reading English usage spec")?,
            &translations,
        )?;
        translate_directory(
            &root.join(format!("docs/{locale}/reference/cli")),
            &translations.markdown,
        )?;
    }
    Ok(())
}

fn translate_labels(source: &str, labels: &BTreeMap<String, String>) -> String {
    let mut output = String::new();
    let mut fenced = false;
    for line in source.lines() {
        if line.starts_with("```") {
            fenced = !fenced;
        }
        if !fenced && line.starts_with("- **Usage:** ") {
            output.push_str(&line.replacen("Usage", &labels["Usage"], 1));
        } else if !fenced
            && let Some(label) = line.strip_prefix("## ").and_then(|label| labels.get(label))
        {
            output.push_str("## ");
            output.push_str(label);
        } else {
            output.push_str(line);
        }
        output.push('\n');
    }
    output
}

#[tracing::instrument(skip_all, err)]
fn translate_directory(directory: &Path, labels: &BTreeMap<String, String>) -> Result<()> {
    for entry in
        fs::read_dir(directory).with_context(|| format!("reading {}", directory.display()))?
    {
        let entry = entry.context("reading reference entry")?;
        let path = entry.path();
        let file_type = entry
            .file_type()
            .with_context(|| format!("reading file type of {}", path.display()))?;
        if file_type.is_symlink() {
            bail!("refusing to follow symlink {}", path.display());
        } else if file_type.is_dir() {
            translate_directory(&path, labels)?;
        } else if path.extension().is_some_and(|extension| extension == "md") {
            let source =
                fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))?;
            fs::write(&path, translate_labels(&source, labels))
                .with_context(|| format!("writing {}", path.display()))?;
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn translations() -> Translations {
        Translations {
            spec: BTreeMap::from([
                ("Print help".into(), "Hilfe anzeigen".into()),
                ("Long\nhelp".into(), "Lange\nHilfe".into()),
            ]),
            markdown: LABELS
                .into_iter()
                .map(|label| (label.into(), format!("de {label}")))
                .collect(),
        }
    }

    #[test]
    fn translates_prose_without_changing_syntax() -> Result<()> {
        let source = "flag \"--help\" help=\"Print help\" action=help builtin=#true\nlong_help #\"\"\"\nLong\nhelp\n\"\"\"#\narg \"[Print help]\"\n";
        let translated = translate_spec(source, &translations())?;
        assert_eq!(
            translated,
            "flag \"--help\" help=\"Hilfe anzeigen\" action=help builtin=#true\nlong_help \"Lange\\nHilfe\"\narg \"[Print help]\"\n"
        );
        Ok(())
    }

    #[cfg(unix)]
    #[test]
    fn refuses_symlinks_in_generated_reference() -> Result<()> {
        let directory = tempfile::tempdir()?;
        let outside = directory.path().join("outside.md");
        let reference = directory.path().join("reference");
        fs::create_dir(&reference)?;
        fs::write(&outside, "## Flags\n")?;
        std::os::unix::fs::symlink(&outside, reference.join("link.md"))?;
        match translate_directory(&reference, &translations().markdown) {
            Ok(()) => bail!("symlink was followed"),
            Err(error) => assert!(error.to_string().contains("symlink")),
        }
        assert_eq!(fs::read_to_string(outside)?, "## Flags\n");
        Ok(())
    }

    #[test]
    fn reports_missing_and_stale_entries() -> Result<()> {
        match translate_spec("about \"Unknown\"", &translations()) {
            Ok(value) => bail!("unexpected translation: {value}"),
            Err(error) => {
                let message = error.to_string();
                assert!(message.contains("Unknown"));
                assert!(message.contains("Print help"));
                assert!(message.contains("stale entries"));
            }
        }
        Ok(())
    }

    #[test]
    fn rejects_malformed_strings() -> Result<()> {
        for source in [
            "help \"unfinished",
            "help #\"\"\"\nunfinished",
            "help \"\\q\"",
        ] {
            match translate_spec(source, &translations()) {
                Ok(value) => bail!("unexpected translation: {value}"),
                Err(error) => assert_ne!(error.to_string(), ""),
            }
        }
        Ok(())
    }

    #[test]
    fn labels_leave_inline_code_and_fenced_examples_unchanged() {
        let source = "- **Usage:** `touchcue`\n## Flags\n`Usage`\n```\n## Flags\n```\n";
        let translated = translate_labels(source, &translations().markdown);
        assert_eq!(
            translated,
            "- **de Usage:** `touchcue`\n## de Flags\n`Usage`\n```\n## Flags\n```\n"
        );
        assert_eq!(
            translate_labels(&translated, &translations().markdown),
            translated
        );
    }

    #[test]
    fn tables_cover_the_cli() -> Result<()> {
        for source in [
            include_str!("../i18n/pl.toml"),
            include_str!("../i18n/de.toml"),
        ] {
            let translations = toml::from_str(source)?;
            translate_spec(&Cli::to_kdl(), &translations)?;
        }
        Ok(())
    }

    #[test]
    fn quoted_translations_round_trip() -> Result<()> {
        let value = "Żółć \"\\\n\t\u{1b} Schlüssel";
        let encoded = quote(value);
        assert_eq!(token(&encoded)?, (value.to_owned(), encoded.len()));
        Ok(())
    }
}
